// Pick question based on days since a fixed epoch
export function getQuestion(date: Date = new Date()): { index: number; text: string } {
  const epoch = new Date('2025-06-24T00:00:00Z');
  const days = Math.floor((date.getTime() - epoch.getTime()) / 86_400_000);
  const index = ((days % QUESTIONS.length) + QUESTIONS.length) % QUESTIONS.length;
  return { index, text: QUESTIONS[index] };
}
